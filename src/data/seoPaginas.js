export function obtenerSeoPagina(pathname) {
  const rutaSeo =
    seoPaginas[pathname]
      ? pathname
      : '/404'

  const seoPagina =
    seoPaginas[rutaSeo]

  return {
    ...seoBase,
    ...seoPagina,
    canonicalPath:
      seoPagina.canonicalPath ??
      rutaSeo,
  }
}
